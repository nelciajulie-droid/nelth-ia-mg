#!/usr/bin/env bun
/**
 * Generate src/lib/skills/catalog.ts from a directory of agent skills
 * (Anthropic agent-skills format: <dir>/<skill-name>/SKILL.md with YAML
 * frontmatter `name` + `description`).
 *
 * Usage:
 *   bun scripts/generate-skill-catalog.mjs <skills-source-dir> [output.ts]
 *
 * The generated catalog is COMMITTED to the repo so runtime code needs no
 * filesystem access (serverless-safe): the skill instructions travel inside
 * the JS bundle.
 *
 * Trimming rules (Claude.ai-style lazy loading):
 *  - manifest keeps name + description trimmed to ~220 chars (first sentences)
 *  - full instructions kept up to MAX_CONTENT_CHARS, cut at a line boundary
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, basename } from 'node:path';

const SRC = process.argv[2];
const OUT = process.argv[3] || 'src/lib/skills/catalog.ts';
const DESC_MAX = 220;
const MAX_CONTENT_CHARS = 24_000;

if (!SRC) {
  console.error('usage: bun scripts/generate-skill-catalog.mjs <skills-source-dir> [output.ts]');
  process.exit(1);
}

/** Minimal YAML frontmatter reader (name/description are plain scalars). */
function parseFrontmatter(md) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(md);
  if (!m) return { name: '', description: '', body: md };
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z_][A-Za-z0-9_-]*):\s*(.*)$/.exec(line);
    if (kv) meta[kv[1].toLowerCase()] = kv[2].trim();
  }
  return { name: meta.name || '', description: meta.description || '', body: md.slice(m[0].length).replace(/^\s+/, '') };
}

function trimDescription(d) {
  if (d.length <= DESC_MAX) return d;
  const cut = d.slice(0, DESC_MAX);
  const stop = Math.max(cut.lastIndexOf('. '), cut.lastIndexOf('! '), cut.lastIndexOf('? '));
  if (stop > 60) return cut.slice(0, stop + 1);
  const sp = cut.lastIndexOf(' ');
  return (sp > 60 ? cut.slice(0, sp) : cut).trimEnd() + '…';
}

function capContent(body) {
  if (body.length <= MAX_CONTENT_CHARS) return body;
  const cut = body.slice(0, MAX_CONTENT_CHARS);
  const nl = cut.lastIndexOf('\n');
  return (nl > MAX_CONTENT_CHARS / 2 ? cut.slice(0, nl) : cut).trimEnd() +
    '\n\n[--- skill instructions truncated for length ---]';
}

const entries = [];
for (const dir of readdirSync(SRC).sort()) {
  const skillMd = join(SRC, dir, 'SKILL.md');
  try {
    if (!statSync(skillMd).isFile()) continue;
  } catch {
    continue;
  }
  const raw = readFileSync(skillMd, 'utf8');
  const { name, description, body } = parseFrontmatter(raw);
  const id = (name || dir).toLowerCase().replace(/[^a-z0-9_-]/g, '-');
  if (!id) continue;
  entries.push({
    name: id,
    label: name || dir,
    description: trimDescription(description || `${dir} skill`),
    content: capContent(body.replace(/\r\n/g, '\n').trim()),
  });
  console.log(`- ${id} (${Math.round(raw.length / 1024)}K → content ${entries[entries.length - 1].content.length} chars)`);
}

const header = `// AUTO-GENERATED by scripts/generate-skill-catalog.mjs — DO NOT EDIT BY HAND.
// Source: Anthropic agent-skills archive (uploaded skills-main.rar).
// Regenerate: bun scripts/generate-skill-catalog.mjs <skills-source-dir>
//
// Claude.ai-style lazy loading: only names + trimmed descriptions go into
// every request (the manifest in the system prompt). A skill's full
// instructions are injected ONLY when the model asks for it with
// USE_SKILL(name) — see src/lib/skills/registry.ts and v12-flow.ts.

export type CatalogSkill = {
  /** Skill id used in USE_SKILL(name) — lowercased, URL-safe. */
  name: string;
  /** Human label from the SKILL.md frontmatter. */
  label: string;
  /** Trimmed frontmatter description (manifest line). */
  description: string;
  /** Full SKILL.md instructions (frontmatter stripped, capped). */
  content: string;
};

export const SKILL_CATALOG: CatalogSkill[] = [
`;

const body = entries
  .map((e) => {
    const desc = JSON.stringify(e.description);
    const label = JSON.stringify(e.label);
    return `  {\n    name: ${JSON.stringify(e.name)},\n    label: ${label},\n    description: ${desc},\n    content: ${JSON.stringify(e.content)},\n  },`;
  })
  .join('\n');

const footer = `
];

export const SKILL_CATALOG_BY_NAME: Record<string, CatalogSkill> = Object.fromEntries(
  SKILL_CATALOG.map((s) => [s.name, s])
);
`;

writeFileSync(OUT, header + body + footer);
console.log(`\nwrote ${OUT}: ${entries.length} skills, manifest ≈ ${entries.reduce((a, e) => a + e.name.length + e.description.length + 12, 0)} chars`);
